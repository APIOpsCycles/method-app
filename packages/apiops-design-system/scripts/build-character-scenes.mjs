await writeFile(outputPath, svg, "utf8");

async function readJson(filePath) {
  return JSON.parse(await readFile(filePath, "utf8"));
}

function renderSceneSymbol(scene) {
  const layers = scene.layers.map((layer, index) => renderLayer(layer, scene.id, index)).join("\n");
  return `    <symbol id="${escapeAttr(scene.id)}" viewBox="${escapeAttr(scene.viewBox)}">\n      <title>${escapeText(scene.title)}</title>\n${layers}\n    </symbol>`;
}

function renderLayer(layer, sceneId, index) {
  switch (layer.type) {
    case "actor":
      if (!registry.poses[layer.pose]) throw new Error(`Unknown character pose "${layer.pose}"`);
      return renderActorLayer(layer, `${sceneId}-actor-${index}`);
    case "symbol": {
      const symbolId = getRegistrySymbolId(layer.symbol);
      const accentClass = layer.accent === true ? "" : " class=\"no-accent\"";
      return `      <g color="${escapeAttr(resolveColor(layer.color))}"${accentClass} transform="translate(${number(layer.x)} ${number(layer.y)})">\n        <use href="#${escapeAttr(prefixSymbolId(symbolId))}" width="${number(layer.width)}" height="${number(layer.height)}" />\n      </g>`;
    }
    case "path":
      return `      <path d="${escapeAttr(layer.d)}" class="${escapeAttr(layer.kind)}" />`;
    case "rect":
      return `      <rect x="${number(layer.x)}" y="${number(layer.y)}" width="${number(layer.width)}" height="${number(layer.height)}" rx="${number(layer.rx ?? 6)}" class="${escapeAttr(layer.class ?? "paper")}" />`;
    case "text":
      return `      <text x="${number(layer.x)}" y="${number(layer.y)}" class="${escapeAttr(layer.class)}" fill="${escapeAttr(resolveColor(layer.color))}">${escapeText(layer.text)}</text>`;
    case "stationLine":
      return renderStationLine(layer);
    default:
      throw new Error(`Unknown scene layer type "${layer.type}"`);
  }
}

function renderActorLayer(layer, clipId) {
  const actorColor = resolveColor(layer.scarfColor ?? layer.color);

  if (layer.crop === "torso") {
    const scaleX = layer.width / 180;
    const scaleY = layer.height / 132;
    const transform = layer.flipX
      ? `translate(${number(layer.x + layer.width)} ${number(layer.y)}) scale(${number(-scaleX)} ${number(scaleY)})`
      : `translate(${number(layer.x)} ${number(layer.y)}) scale(${number(scaleX)} ${number(scaleY)})`;

    return `      <clipPath id="${escapeAttr(clipId)}">
        <rect x="0" y="0" width="180" height="132" />
      </clipPath>
      <g color="${escapeAttr(actorColor)}" transform="${transform}" clip-path="url(#${escapeAttr(clipId)})">
        <use href="#scene-actor-${escapeAttr(layer.pose)}" width="180" height="205" />
      </g>`;
  }

  const transform = layer.flipX
    ? `translate(${number(layer.x)} ${number(layer.y)}) scale(-1 1) translate(-${number(layer.width)} 0)`
    : `translate(${number(layer.x)} ${number(layer.y)})`;

  return `      <g color="${escapeAttr(actorColor)}" transform="${transform}">\n        <use href="#scene-actor-${escapeAttr(layer.pose)}" width="${number(layer.width)}" height="${number(layer.height)}" />\n      </g>`;
}

function renderStationLine(layer) {
  const stations = layer.stations
    .map(
      (station) => `        <g color="${escapeAttr(resolveColor(station.color))}">
          <circle cx="${number(station.x)}" cy="${number(layer.y)}" r="8" class="accent" />
          <text x="${number(station.x)}" y="${number(layer.y + 27)}" class="tiny" fill="${escapeAttr(resolveColor(station.color))}">${escapeText(station.label)}</text>
        </g>`,
    )
    .join("\n");

  return `      <path d="M${number(layer.x1)} ${number(layer.y)} H${number(layer.x2)}" class="body" />\n${stations}`;
}

function renderPreviewCard(card) {
  return `  <g transform="translate(${number(card.x)} ${number(card.y)})">
    <rect width="${number(card.width)}" height="${number(card.height)}" rx="12" class="soft" />
    <g transform="translate(${number(card.sceneX)} ${number(card.sceneY)})">
      <use href="#${escapeAttr(card.scene)}" width="${number(card.sceneWidth)}" height="${number(card.sceneHeight)}" />
    </g>
    <text x="${number(card.titleX)}" y="${number(card.titleY)}" class="label" fill="${escapeAttr(resolveColor(card.color))}">${escapeText(card.title)}</text>
  </g>`;
}

async function collectNotationSymbol(symbolId) {
  if (notationIds.has(symbolId)) return;
  const symbol = await readNotationSymbol(symbolId);
  notationIds.add(symbolId);
  notationSources.set(symbolId, symbol);

  const dependencies = [...symbol.matchAll(/href="#((?:symbol|connection)-[^"]+)"/g)].map((match) => match[1]);
  for (const dependency of dependencies) {
    await collectNotationSymbol(dependency);
  }
}

async function readNotationSymbol(symbolId) {
  const notationPath = path.join(assetsRoot, "icons", "apiops-character-notation.svg");
  const notation = await readFile(notationPath, "utf8");
  const match = notation.match(new RegExp(`<symbol\\s+id="${escapeRegExp(symbolId)}"(?:\\s|>)[\\s\\S]*?<\\/symbol>`));
  if (!match) throw new Error(`Missing notation symbol "${symbolId}"`);
  return match[0];
}

function rewriteNotationSymbol(symbol) {
  return removeNotationAccents(symbol)
    .replace(/<symbol\s+id="((?:symbol|connection)-[^"]+)"/, (_, id) => `<symbol id="${prefixSymbolId(id)}"`)
    .replace(/href="#((?:symbol|connection)-[^"]+)"/g, (_, id) => `href="#${prefixSymbolId(id)}"`);
}

function removeNotationAccents(symbol) {
  return symbol
    .replace(/\s*<[^>]+class="accent"[^>]*\/>/g, "")
    .replace(/\s*<([a-zA-Z]+)\b[^>]*class="accent"[^>]*>[\s\S]*?<\/\1>/g, "");
}

function getRegistrySymbolId(alias) {
  const source = registry.symbols[alias];
  if (!source) throw new Error(`Unknown notation symbol "${alias}"`);
  const [, symbolId] = source.split("#");
  if (!symbolId) throw new Error(`Notation symbol "${alias}" must include a fragment id`);
  return symbolId;
}

function prefixSymbolId(symbolId) {
  return `scene-${symbolId}`;
}

function getViewBox(svg, source) {
  const match = svg.match(/\bviewBox="([^"]+)"/);
  if (!match) throw new Error(`Missing viewBox in ${source}`);
  return match[1];
}

function extractSvgBody(svg, source) {
  const body = svg.match(/<svg\b[^>]*>([\s\S]*)<\/svg>/)?.[1];
  if (!body) throw new Error(`Unable to read SVG body for ${source}`);
  return body.replace(/<sodipodi:namedview\b[\s\S]*?\/>/g, "").replace(/<defs\b[\s\S]*?<\/defs>/g, "").trim();
}

function stripSvgMetadata(svg) {
  return svg
    .replace(/\s(?:sodipodi|inkscape):[a-zA-Z0-9-]+="[^"]*"/g, "")
    .replace(/\sxmlns(?::[a-zA-Z0-9-]+)?="[^"]*"/g, "")
    .replace(/\sid="[^"]*"/g, "")
    .replace(/#1656b8/gi, "currentColor")
    .trim();
}

function resolveColor(value) {
  if (!value) return registry.colors.community;
  return registry.colors[value] ?? value;
}

function escapeText(value) {
  return String(value).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
}

function escapeAttr(value) {
  return escapeText(value).replace(/"/g, "&quot;");
}

function escapeRegExp(value) {
  return String(value).replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

function indent(value, spaces) {
  const prefix = " ".repeat(spaces);
  return value
    .split("\n")
    .map((line) => (line.trim() ? `${prefix}${line}` : line))
    .join("\n");
}

function number(value) {
  if (!Number.isFinite(value)) throw new Error(`Expected finite number, got ${value}`);
  return Number.isInteger(value) ? String(value) : String(Number(value.toFixed(3)));
}
